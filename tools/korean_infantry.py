def vanilla(path):
    out = subprocess.run([sys.executable, korean_visuals.BARTOOL, 'cat', path], capture_output=True, check=True)
    return out.stdout.decode('utf-8-sig').replace('\r\n', '\n')


def animfile(unit):
    u = UNITS[unit]
    own = BS.join(['units', unit, ''])
    text = vanilla(u['src'])
    pattern = r'<file>%s%s%s([%s])</file>' % (re.escape(u['van']), '(?:lp_)?' if u['lp'] else '', u['body'],
                                               ''.join(str(a) for a in u['ages']))
    remap = u.get('remap', {})
    text, n = re.subn(pattern, lambda m: '<file>%s%s_age%s</file>' % (own, unit, remap.get(int(m.group(1)), m.group(1))),
                      text)
    assert n == 6, '%s: expected 6 body models (3 ages, normal + low poly), found %d' % (unit, n)
    for old, new in u['techs'].items():
        text, n = re.subn(r'(</?)%s>' % old, r'\1%s>' % new, text)
        assert n == 2, '%s: %d tags' % (old, n)
    for tag, index in u.get('variant', {}).items():      # the vanilla grammar: <materialvariant> after the <file>
        i, j = text.index('<%s>' % tag), text.index('</%s>' % tag)
        branch, n = re.subn(r'( *)(<file>%s[^<]*</file>)\n' % re.escape(own),
                            lambda m: '%s%s\n%s<materialvariant index="%d" />\n' % (m.group(1), m.group(2), m.group(1), index),
                            text[i:j])
        assert n == 2, '%s: %d body models' % (tag, n)
        text = text[:i] + branch + text[j:]
    if unit == 'korean_jochong':
        hat = re.escape(u['van'] + 'arquebusier_age3_hat')
        text, n = re.subn(r'<file>%s</file>' % hat, lambda m: '<file>%skorean_jochong_hat</file>' % own, text)
        assert n == 1, 'expected one hat attachment, found %d' % n
        # age 1 has no hat in vanilla: the jeollip on every age (after the gun, as vanilla age 2/3 normal models)
        none = re.search(r'<none>.*?</none>', text, re.S).group(0)
        gun1 = '<attach a="gun_age1" frombone="bone_gun" tobone="BIP01 PROP1" syncanims="0" />'
        assert HAT_ATTACH not in none and none.count(gun1) == 2
        text = text.replace(none, none.replace(gun1, gun1 + '\n            ' + HAT_ATTACH))
        assert text.count(HAT_ATTACH) == 6
    if unit == 'korean_gakgung':
        old = '<attachment>bows<include>%s</include>\n  </attachment>' % LONGBOWS
        new = ('<attachment>bows<component>bows<assetreference type="GrannyModel">\n        <file>%s</file>\n'
               '      </assetreference>\n    </component>\n    <anim>Idle<component>bows</component>\n    </anim>\n'
               '  </attachment>') % AZAP_BOW
        assert text.count(old) == 1, 'the Yumi bow set changed'
        text = text.replace(old, new)
    assert not re.search(r'%s(lp_)?%s[0-9]</file>' % (re.escape(u['van']), u['body']), text), unit
    return text


def vanilla_materialdef(folder, model):
    """The vanilla model's materialdef, copied: it differs per model (changdao_0 default_doublesided, changdao_1 and 2
    default_doublesided_cutout - only the cutout one cuts the cards by the BaseColor alpha; one value per unit drew
    the Gakgung's cards as solid squares, owner's test 2026-10-09)."""
    text = vanilla('Art/' + (folder + model).replace(BS, '/') + '.material.XMB')
    defs = set(re.findall(r'<materialdef name="([^"]+)"', text))
    assert len(defs) == 1, (model, defs)
    return defs.pop()


def material(unit, model, sub, van, maps, variants=None):
    u = UNITS[unit]
    md = vanilla_materialdef(u.get('tex', u['van']), van) if van else 'default'   # the crafted jeollip: default
    lines = ['<material>', '  <submaterial name="%s">' % sub, '    <materialdef name="%s" />' % md]
    for index, ms in [(None, maps)] + sorted((variants or {}).items()):
        lines.append('    <parameters>' if index is None else '    <parameters variant="%d">' % index)
        for ch, own in ms.items():
            if own:
                path = 'units/%s/textures/%s_matA_%s' % (unit, own if isinstance(own, str) else model, ch)
            else:
                path = u.get('tex', u['van']) + 'textures' + BS + '%s_%s_%s' % (van, sub, ch)
            lines.append('      <texture name="%s" override="%s" />' % (ch, path))
        lines.append('    </parameters>')
    return '\n'.join(lines + ['  </submaterial>', '</material>', ''])


def build():
    out = {}
    for unit, u in UNITS.items():
        out['art/units/%s/%s.xml' % (unit, unit)] = animfile(unit)
        for model, spec in u['materials'].items():
            out['art/units/%s/%s.material' % (unit, model)] = material(unit, model, *spec)
    return {p: t.replace('\n', '\r\n').encode('utf-8') for p, t in out.items()}


def main():
    for path, data in build().items():
        print('%-52s %7d bytes' % (path, len(data)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
